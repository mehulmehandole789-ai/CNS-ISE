import json
import pickle
import platform
import shutil
import time
from datetime import datetime, timezone

import joblib
import numpy as np
import optuna
import pandas as pd
import pyarrow.parquet as pq
import sklearn

from sklearn.svm import NuSVC
from sklearn.metrics import (
    accuracy_score,
    balanced_accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
)

manifest = pd.read_parquet(MANIFEST_PATH)

# Detect column names.
column_map = {
    str(col).lower().replace("_", ""): col
    for col in manifest.columns
}

id_col = column_map.get("sampleid")
label_col = (
    column_map.get("labelcanonical")
    or column_map.get("label")
)
split_col = column_map.get("split")

if any(col is None for col in [id_col, label_col, split_col]):
    raise ValueError(
        "Manifest needs sample_id, label/label_canonical, and split. "
        f"Available columns: {list(manifest.columns)}"
    )

if manifest[[id_col, label_col, split_col]].isna().any().any():
    raise ValueError("Manifest has missing IDs, labels, or splits.")

if manifest[id_col].duplicated().any():
    raise ValueError("Manifest has duplicate sample IDs.")

manifest = manifest.set_index(id_col)
manifest[label_col] = manifest[label_col].astype(str)

splits = (
    manifest[split_col]
    .astype(str)
    .str.strip()
    .str.lower()
)

train_idx = manifest.index[splits.eq("train")]
val_idx = manifest.index[splits.isin(["val", "validation"])]
test_idx = manifest.index[splits.eq("test")]

for name, ids in [
    ("Train", train_idx),
    ("Validation", val_idx),
    ("Test", test_idx),
]:
    if len(ids) == 0:
        raise ValueError(f"{name} split is empty.")
    print(f"{name}: {len(ids)} samples")

with open(FEATURE_SELECTION_PATH, "r", encoding="utf-8") as f:
    selection = json.load(f)

base_features = selection[MODALITY]["methods"][METHOD][K]

if (
    not isinstance(base_features, list)
    or not all(isinstance(name, str) for name in base_features)
):
    raise ValueError("Feature selection must be a list of column names.")

if len(base_features) != int(K):
    raise ValueError(
        f"Expected {K} features, found {len(base_features)}."
    )

if len(set(base_features)) != len(base_features):
    raise ValueError("Feature selection contains duplicate columns.")

schema_columns = set(
    pq.ParquetFile(FEATURES_PATH).schema_arrow.names
)

if all(name in schema_columns for name in base_features):
    featcolsused = list(base_features)
    feature_mode = "exact"

elif all(f"{name}scaled" in schema_columns for name in base_features):
    featcolsused = [f"{name}scaled" for name in base_features]
    feature_mode = "scaled_suffix"

else:
    raise ValueError(
        "Selected features do not match the feature Parquet columns."
    )

# Prevent labels and split metadata from becoming model inputs.
metadata_names = {
    "sampleid", "label", "labelcanonical",
    "class", "split", "dupgroup",
}

leaked = [
    name for name in featcolsused
    if name.lower().replace("_", "") in metadata_names
]

if leaked:
    raise ValueError(f"Metadata selected as features: {leaked}")

if id_col not in schema_columns:
    raise ValueError(f"Feature file is missing ID column: {id_col}")

feature_table = pd.read_parquet(
    FEATURES_PATH,
    columns=[id_col] + featcolsused,
)

if feature_table[id_col].isna().any():
    raise ValueError("Feature file has missing sample IDs.")

if feature_table[id_col].duplicated().any():
    raise ValueError("Feature file has duplicate sample IDs.")

feature_table = feature_table.set_index(id_col)


def prepare_split(ids):
    missing_ids = ids.difference(feature_table.index)

    if len(missing_ids):
        raise ValueError(
            f"{len(missing_ids)} sample IDs are missing "
            "from the feature file."
        )

    X = feature_table.loc[
        ids, featcolsused
    ].to_numpy(dtype=np.float32)

    y = manifest.loc[ids, label_col].to_numpy()

    if not np.isfinite(X).all():
        raise ValueError("Features contain NaN or infinite values.")

    return X, y


Xtrain, ytrain = prepare_split(train_idx)
Xval, yval = prepare_split(val_idx)
Xtest, ytest = prepare_split(test_idx)

classes, class_counts = np.unique(ytrain, return_counts=True)

if len(classes) < 2:
    raise ValueError("Training requires at least two classes.")

for name, labels in [("Validation", yval), ("Test", ytest)]:
    unseen = set(labels) - set(classes)
    if unseen:
        raise ValueError(
            f"{name} has classes absent from training: {unseen}"
        )

print("Train shape:", Xtrain.shape)
print("Validation shape:", Xval.shape)
print("Test shape:", Xtest.shape)
print("Feature mode:", feature_mode)
print("Classes:", classes)
print("\nData is ready for training.")

# Calculate a feasible nu range using training class counts.
pair_limits = [
    2.0 * min(class_counts[i], class_counts[j])
    / (class_counts[i] + class_counts[j])
    for i in range(len(classes))
    for j in range(i + 1, len(classes))
]

nu_upper = min(0.20, 0.95 * min(pair_limits))
nu_lower = min(0.01, nu_upper / 10.0)


def objective(trial):
    model = NuSVC(
        kernel="rbf",
        gamma=trial.suggest_float(
            "gamma", 1e-4, 1e-1, log=True
        ),
        nu=trial.suggest_float(
            "nu", nu_lower, nu_upper
        ),
        cache_size=1000,
        max_iter=-1,
        random_state=RANDOM_STATE,
    )

    try:
        model.fit(Xtrain, ytrain)
    except ValueError as error:
        if "specified nu is infeasible" in str(error).lower():
            raise optuna.TrialPruned(str(error))
        raise

    val_predictions = model.predict(Xval)

    return float(
        balanced_accuracy_score(yval, val_predictions)
    )


study = optuna.create_study(
    direction="maximize",
    sampler=optuna.samplers.TPESampler(seed=RANDOM_STATE),
)

start = time.perf_counter()

study.optimize(
    objective,
    n_trials=OPTUNA_TRIALS,
    show_progress_bar=True,
)

tuning_seconds = time.perf_counter() - start

completed_trials = [
    trial for trial in study.trials
    if trial.state == optuna.trial.TrialState.COMPLETE
]

if not completed_trials:
    raise RuntimeError("No tuning trials completed successfully.")

print("\nBest parameters:", study.best_params)
print("Validation balanced accuracy:", round(study.best_value, 4))

final_model = NuSVC(
    **study.best_params,
    kernel="rbf",
    cache_size=1000,
    max_iter=-1,
    random_state=RANDOM_STATE,
)

start = time.perf_counter()
final_model.fit(Xtrain, ytrain)
train_seconds = time.perf_counter() - start

start = time.perf_counter()
ytest_pred = final_model.predict(Xtest)
inference_seconds = time.perf_counter() - start

metrics = {
    "test_accuracy": float(
        accuracy_score(ytest, ytest_pred)
    ),
    "test_balanced_accuracy": float(
        balanced_accuracy_score(ytest, ytest_pred)
    ),
    "test_macro_f1": float(
        f1_score(
            ytest, ytest_pred,
            average="macro", zero_division=0
        )
    ),
    "test_weighted_f1": float(
        f1_score(
            ytest, ytest_pred,
            average="weighted", zero_division=0
        )
    ),
    "best_validation_balanced_accuracy": float(study.best_value),
    "training_samples": len(ytrain),
    "validation_samples": len(yval),
    "test_samples": len(ytest),
    "n_features": len(featcolsused),
    "tuning_seconds": tuning_seconds,
    "training_seconds": train_seconds,
    "inference_seconds": inference_seconds,
}

report_options = {
    "labels": classes,
    "target_names": [str(label) for label in classes],
    "zero_division": 0,
}

report_text = classification_report(
    ytest, ytest_pred, **report_options
)

print("FINAL TEST METRICS")
print(json.dumps(metrics, indent=2))
print("\nCLASSIFICATION REPORT")
print(report_text)

def json_default(value):
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, np.generic):
        return value.item()
    if isinstance(value, Path):
        return str(value)
    raise TypeError(f"Unsupported JSON type: {type(value).__name__}")


def save_json(filename, content):
    with open(OUTPUT_PATH / filename, "w", encoding="utf-8") as f:
        json.dump(
            content,
            f,
            indent=2,
            ensure_ascii=False,
            default=json_default,
            allow_nan=False,
        )


